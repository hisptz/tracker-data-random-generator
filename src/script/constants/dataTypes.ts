function timeToMinutes(time: string | undefined, fallback: number): number {
	if (!time) {
		return fallback;
	}
	const [hours, minutes] = time.split(":").map(Number);
	if (isNaN(hours)) {
		return fallback;
	}
	return hours * 60 + (isNaN(minutes) ? 0 : minutes);
}

// DHIS2 TIME values are formatted as HH:mm
function generateTime({ mode, value, from, to }: ExactOrRangeParams = {}) {
	if (mode === "exact") {
		return formatMinutes(timeToMinutes(value, 0));
	}
	const start = timeToMinutes(from, 0);
	const end = timeToMinutes(to, 23 * 60 + 59);
	const totalMinutes = faker.number.int({
		min: Math.min(start, end),
		max: Math.max(start, end),
	});
	return formatMinutes(totalMinutes);
}

function formatMinutes(totalMinutes: number) {
	const hours = Math.floor(totalMinutes / 60);
	const minutes = totalMinutes % 60;
	return `${String(hours).padStart(2, "0")}:${String(minutes).padStart(2, "0")}`;
}

