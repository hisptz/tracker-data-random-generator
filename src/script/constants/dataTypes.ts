interface ExactOrRangeParams {
	mode?: "exact" | "range";
	value?: string;
	from?: string;
	to?: string;
}

function generateDateTime({ mode, value, from, to }: ExactOrRangeParams = {}) {
	const now = new Date();
	if (mode === "exact") {
		return (value ? parseLocalDateTime(value) : now).toISOString();
	}
	const fromDate = from
		? parseLocalDateTime(from)
		: new Date(new Date().setFullYear(now.getFullYear() - 1));
	const toDate = to ? parseLocalDateTime(to, true) : now;
	const [start, end] =
		fromDate <= toDate ? [fromDate, toDate] : [toDate, fromDate];
	return faker.date.between({ from: start, to: end }).toISOString();
}

// Parses "yyyy-MM-dd" or "yyyy-MM-ddTHH:mm" as local time. A date-only value
// used as an upper bound covers the whole of that day.
function parseLocalDateTime(value: string, endOfDay = false): Date {
	if (!value.includes("T")) {
		return new Date(`${value}T${endOfDay ? "23:59:59.999" : "00:00:00"}`);
	}
	return new Date(value);
}

