function generateAutogeneratedValuesQuery(
	values: DataItemConfig[],
	count: number,
	orgUnitCode: string,
) {
	return fromPairs(
		values.map(({ dataItemId }) => [
			dataItemId,
			{
				resource: "trackedEntityAttributes",
				id: `${dataItemId}/generateAndReserve`,
				params: {
					numberToReserve: count,
					ORG_UNIT_CODE: orgUnitCode,
				},
			},
		]),
	);
}

function sanitizeParam(param: any, config?: SupportedParam) {
	if (!config) {
		return param;
	}
	switch (config.type) {
		case "number":
			return Number(param);
		default:
			return param;
	}
}

/*
 * Converts a generated value to the string format the DHIS2 value type validation expects
 * (see ValidationUtils.valueIsValid in dhis-support-system).
 * Returns undefined when there is no value so that the data value can be omitted.
 */
function formatValue(value: unknown, dataTypeName?: string) {
	if (value === undefined || value === null || value === "") {
		return;
	}
	if (
		dataTypeName === SupportedDataTypeNames.COORDINATES &&
		Array.isArray(value)
	) {
		// faker returns [latitude, longitude], DHIS2 expects [longitude,latitude]
		const [latitude, longitude] = value;
		return `[${Number(longitude).toFixed(2)},${Number(latitude).toFixed(2)}]`;
	}
	if (value instanceof Date) {
		return DateTime.fromJSDate(value).toFormat("yyyy-MM-dd");
	}
	return `${value}`;
}

function generateValue(config: DataItemConfig): string | undefined {
	const { dataTypeName, options } = config ?? {};
	const dataGenerationConfig = find(supportedDataTypes, [
		"name",
		dataTypeName,
	]);
	if (!dataGenerationConfig) {
		return;
	}

	const params = compact(
		isEmpty(options?.params)
			? dataGenerationConfig.defaultParams ?? []
			: options?.params?.map((param, index) => {
					if (!isEmpty(param) || typeof param === "number") {
						const paramType =
							dataGenerationConfig.supportedParams?.[index];
						return sanitizeParam(param, paramType);
					}
					return dataGenerationConfig.defaultParams?.[index];
				}),
	);

	if (dataGenerationConfig.name === SupportedDataTypeNames.TRUE_ONLY) {
		params.unshift(head(dataGenerationConfig.defaultParams));
	}

	if (dataGenerationConfig.name === SupportedDataTypeNames.OPTIONS) {
		if (isEmpty(head(params))) {
			return;
		}
		return formatValue(dataGenerationConfig.fn(head(params)));
	}

	return formatValue(dataGenerationConfig.fn(...params), dataTypeName);
}

function generateDataValues(configs?: DataItemConfig[]): TrackerDataValue[] {
	return compact(configs).flatMap((config) => {
		const value = generateValue(config);
		return value === undefined
			? []
			: [{ dataElement: config.dataItemId, value }];
	});
}

function randomDateBetween({ min, max }: { min: Date; max: Date }): string {
	if (max <= min) {
		return min.toISOString();
	}
	return faker.date.between({ from: min, to: max }).toISOString();
}

function parseDate(date?: string): Date | undefined {
	if (!date) {
		return;
	}
	const parsed = new Date(date);
	return isNaN(parsed.getTime()) ? undefined : parsed;
}

function getEndOfDay(date?: string): Date | undefined {
	const parsed = parseDate(date);
	if (!parsed) {
		return;
	}
	return DateTime.fromJSDate(parsed).endOf("day").toJSDate();
}

/*
 * Resolves a time boundary, defaulting the missing ends and never going past today
 */
function resolveBoundary(
	boundary: TimeBoundary | undefined,
	defaults: { min: Date; max: Date },
): { min: Date; max: Date } {
	const now = new Date();
	const min = parseDate(boundary?.min) ?? defaults.min;
	const requestedMax = getEndOfDay(boundary?.max) ?? defaults.max;
	const max = requestedMax > now ? now : requestedMax;
	return { min, max: max < min ? min : max };
}

function pickOrgUnit(orgUnits?: { id: string }[]): string {
	const ids = orgUnits?.map(({ id }) => id) ?? [];
	if (isEmpty(ids)) {
		throw new Error("At least one organisation unit is required");
	}
	return faker.helpers.arrayElement(ids);
}

export class EventRandomDataEngine {
	config: EventProgramDataConfiguration;
	program: Program;
	engine: DataEngine;
	stage: ProgramStage;

	constructor({
		config,
		program,
		engine,
	}: {
		config: EventProgramDataConfiguration;
		program: Program;
		engine: DataEngine;
	}) {
		this.config = config;
		this.engine = engine;
		this.program = program;
		this.stage = head(this.program.programStages) as ProgramStage;

		if (this.config.meta.locale) {
			// @ts-expect-error setLocale is not available in all faker versions
			faker.setLocale(this.config.meta.locale);
		}
	}

	async generate({ count }: GenerateProps): Promise<TrackerPayload> {
		return {
			trackedEntities: [],
			enrollments: [],
			events: times(count, () => this.generateEvent()),
		};
	}

	generateEvent(): TrackerEvent {
		const { meta } = this.config;
		const boundary = resolveBoundary(meta?.eventTimeBoundary, {
			min: DateTime.now().minus({ years: 1 }).toJSDate(),
			max: new Date(),
		});
		const occurredAt = randomDateBetween(boundary);

		return {
			event: uid(),
			program: this.program.id,
			programStage: this.stage.id,
			orgUnit: pickOrgUnit(meta.orgUnits),
			occurredAt,
			status: "COMPLETED",
			completedAt: occurredAt,
			dataValues: generateDataValues(this.config.dataElements),
		};
	}
}

export class TrackerRandomDataEngine {
	config: DataConfiguration;
	program: Program;
	engine: DataEngine;
	autogenerated?: {
		[key: string]: string[];
	};

	constructor({
		config,
		program,
		engine,
	}: {
		config: DataConfiguration;
		program: Program;
		engine: DataEngine;
	}) {
		this.config = config;
		this.engine = engine;
		this.program = program;

		if (this.config.meta.locale) {
			// @ts-expect-error setLocale is not available in all faker versions
			faker.setLocale(this.config.meta.locale);
		}
	}

	async generateWithPagination({
		pages,
		pageSize,
	}: GenerateWithPaginationProps): Promise<TrackerPayload[]> {
		const teiPages: TrackerPayload[] = [];
		for (let page = 0; page < pages; page++) {
			teiPages.push(await this.generate({ count: pageSize ?? 50 }));
		}
		return teiPages;
	}

	async getAutogeneratedValues(count: number) {
		const autogeneratedAttributes = compact(this.config.attributes).filter(
			({ dataTypeName }) => {
				return dataTypeName === SupportedDataTypeNames.AUTOGENERATED;
			},
		);
		if (isEmpty(autogeneratedAttributes)) {
			return;
		}

		const orgUnit = head(this.config.meta.orgUnits) as any;

		const query = generateAutogeneratedValuesQuery(
			autogeneratedAttributes,
			count,
			orgUnit?.code,
		);
		const values = await this.engine.query(query);

		this.autogenerated = mapValues(
			values,
			(value: Record<string, string>[]) => {
				return value.map(({ value }) => value);
			},
		) as unknown as { [key: string]: string[] };
	}

	async generate({ count }: GenerateProps): Promise<TrackerPayload> {
		await this.getAutogeneratedValues(count);
		const records = times(count, (index) =>
			this.generateTrackedEntity(index),
		);
		return {
			trackedEntities: records.map(({ trackedEntity }) => trackedEntity),
			enrollments: records.map(({ enrollment }) => enrollment),
			events: flatten(records.map(({ events }) => events)),
		};
	}

	generateAttributes(teiIndex: number): TrackerAttributeValue[] {
		return compact(this.config.attributes).flatMap((config) => {
			const value =
				config.dataTypeName === SupportedDataTypeNames.AUTOGENERATED
					? get(this.autogenerated, [config.dataItemId, teiIndex])
					: generateValue(config);
			return value === undefined || value === null
				? []
				: [{ attribute: config.dataItemId, value: `${value}` }];
		});
	}

	getNumberOfEvents(programStageId: string, count?: number): number {
		const programStage = find(this.program.programStages, [
			"id",
			programStageId,
		]);
		if (!programStage) {
			return 0;
		}
		if (!programStage.repeatable) {
			return 1;
		}
		const numberOfEvents = parseInt(String(count ?? 1));
		return isNaN(numberOfEvents) ? 1 : Math.max(numberOfEvents, 0);
	}

	generateEnrollmentEvents({
		enrolledAt,
		...props
	}: {
		enrolledAt: string;
		enrollment: string;
		trackedEntity: string;
		orgUnit: string;
	}): TrackerEvent[] {
		const enrollmentDate = new Date(enrolledAt);

		const events = flatten(
			compact(this.config.programStages).map(
				({ id, eventTimeBoundary, dataElements, count }) => {
					// Events can only happen between the enrollment date and today
					const boundary = resolveBoundary(eventTimeBoundary, {
						min: enrollmentDate,
						max: new Date(),
					});
					if (boundary.min < enrollmentDate) {
						boundary.min = enrollmentDate;
						if (boundary.max < enrollmentDate) {
							boundary.max = enrollmentDate;
						}
					}

					return times(
						this.getNumberOfEvents(id, count),
						(): TrackerEvent => {
							const occurredAt = randomDateBetween(boundary);
							return {
								...props,
								event: uid(),
								program: this.program.id,
								programStage: id,
								occurredAt,
								status: "COMPLETED",
								completedAt: occurredAt,
								dataValues: generateDataValues(dataElements),
							};
						},
					);
				},
			),
		);

		return sortBy(events, "occurredAt");
	}

	generateTrackedEntity(teiIndex: number): {
		trackedEntity: TrackerTrackedEntity;
		enrollment: TrackerEnrollment;
		events: TrackerEvent[];
	} {
		const { trackedEntityType, enrollmentTimeBoundary, orgUnits } =
			this.config.meta;
		if (!trackedEntityType) {
			throw new Error("The program has no tracked entity type");
		}

		const enrolledAt = randomDateBetween(
			resolveBoundary(enrollmentTimeBoundary, {
				min: DateTime.now().minus({ years: 1 }).toJSDate(),
				max: new Date(),
			}),
		);
		const orgUnit = pickOrgUnit(orgUnits);
		const trackedEntity = uid();
		const enrollment = uid();

		return {
			trackedEntity: {
				trackedEntity,
				trackedEntityType,
				orgUnit,
				attributes: this.generateAttributes(teiIndex),
			},
			enrollment: {
				enrollment,
				trackedEntity,
				program: this.program.id,
				orgUnit,
				status: "ACTIVE",
				enrolledAt,
				occurredAt: enrolledAt,
			},
			events: this.generateEnrollmentEvents({
				enrolledAt,
				enrollment,
				trackedEntity,
				orgUnit,
			}),
		};
	}
}
