import { describe, expect, it } from "@jest/globals";
import { SupportedDataTypeNames } from "../../../../script/constants/dataTypes";
import { DataItem } from "../generators";
import { suggestGenerator } from "../suggestions";

function item(name: string, valueType: string, extra = {}): DataItem {
	return { id: `${name}-id`, name, valueType, ...extra } as unknown as DataItem;
}

describe("suggestGenerator", () => {
	it("uses name hints for text fields", () => {
		expect(suggestGenerator(item("First name", "TEXT"))?.dataTypeName).toBe(
			SupportedDataTypeNames.FIRST_NAME,
		);
		expect(suggestGenerator(item("Surname", "TEXT"))?.dataTypeName).toBe(
			SupportedDataTypeNames.LAST_NAME,
		);
		expect(
			suggestGenerator(item("Mobile phone number", "TEXT"))?.dataTypeName,
		).toBe(SupportedDataTypeNames.PHONE_NUMBER);
		expect(suggestGenerator(item("E-mail", "TEXT"))?.dataTypeName).toBe(
			SupportedDataTypeNames.EMAIL,
		);
		expect(suggestGenerator(item("Patient name", "TEXT"))?.dataTypeName).toBe(
			SupportedDataTypeNames.FULL_NAME,
		);
	});

	it("prefers the form name over the name", () => {
		const attribute = item("TEA 12", "TEXT", { formName: "Given name" });
		expect(suggestGenerator(attribute)?.dataTypeName).toBe(
			SupportedDataTypeNames.FIRST_NAME,
		);
	});

	it("ignores name hints the value type can't use", () => {
		// ID only supports TEXT, so a NUMBER field named "number" falls back to its value type
		expect(
			suggestGenerator(item("Number of children", "NUMBER"))?.dataTypeName,
		).toBe(SupportedDataTypeNames.NUMBER);
		expect(
			suggestGenerator(item("Facility name", "TEXT"))?.dataTypeName,
		).toBe(SupportedDataTypeNames.RANDOM_WORDS);
	});

	it("falls back to value type defaults", () => {
		expect(suggestGenerator(item("Visit date", "DATE"))?.dataTypeName).toBe(
			SupportedDataTypeNames.PAST_DATE,
		);
		expect(suggestGenerator(item("Pregnant", "BOOLEAN"))?.dataTypeName).toBe(
			SupportedDataTypeNames.BOOLEAN,
		);
		expect(suggestGenerator(item("Remarks", "LONG_TEXT"))?.dataTypeName).toBe(
			SupportedDataTypeNames.LONG_TEXT,
		);
		expect(suggestGenerator(item("Location", "COORDINATE"))?.dataTypeName).toBe(
			SupportedDataTypeNames.COORDINATES,
		);
	});

	it("keeps numbers in a realistic range", () => {
		expect(suggestGenerator(item("Weight", "NUMBER"))).toEqual({
			dataTypeName: SupportedDataTypeNames.NUMBER,
			options: { params: [{ min: 0, max: 100 }] },
		});
		expect(suggestGenerator(item("Doses", "INTEGER_POSITIVE"))).toEqual({
			dataTypeName: SupportedDataTypeNames.POSITIVE_NUMBER,
			options: { params: [{ min: 1, max: 100 }] },
		});
	});

	it("gives IDs a useful length", () => {
		expect(suggestGenerator(item("National ID", "TEXT"))).toEqual({
			dataTypeName: SupportedDataTypeNames.ID,
			options: { params: [10] },
		});
	});

	it("selects every option of an option set", () => {
		const field = item("Sex", "TEXT", {
			optionSet: {
				id: "os",
				options: [
					{ id: "1", code: "F", name: "Female" },
					{ id: "2", code: "M", name: "Male" },
				],
			},
		});
		expect(suggestGenerator(field)).toEqual({
			dataTypeName: SupportedDataTypeNames.OPTIONS,
			options: { params: [["F", "M"]] },
		});
	});

	it("uses the autogenerated generator for generated attributes", () => {
		expect(
			suggestGenerator(item("Unique ID", "TEXT", { generated: true }))
				?.dataTypeName,
		).toBe(SupportedDataTypeNames.AUTOGENERATED);
	});

	it("returns nothing when no generator supports the field", () => {
		expect(suggestGenerator(item("Photo", "IMAGE"))).toBeUndefined();
	});
});
